import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';

const root = path.resolve('dist/client');
async function files(directory) {
  const result = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const name = path.join(directory, entry.name);
    if (entry.isDirectory()) result.push(...await files(name));
    else result.push(name);
  }
  return result;
}
// Include every build chunk: lazy-loaded quiz and dictionary must work offline.
const assets = (await files(root)).filter(name => /\.(js|css|woff2|png|svg|webmanifest)$/.test(name));
const urls = assets.map(name => '/' + path.relative(root, name).replaceAll('\\', '/'));
const hash = createHash('sha256');
for (const name of assets.sort()) hash.update(await readFile(name));
const version = hash.digest('hex').slice(0, 16);
const source = `/* Generated by scripts/build-pwa.mjs. API/auth traffic is never cached. */
const CACHE = 'vocabdna-pwa-${version}';
const ASSETS = ${JSON.stringify(urls)};
self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await cache.addAll(ASSETS);
    const response = await fetch('/', { credentials: 'same-origin', cache: 'no-store' });
    // Never cache a sign-in page or a redirect as the offline app.
    if (!response.ok || response.redirected || !(await response.clone().text()).includes('VocabDNA')) throw new Error('App unavailable');
    await cache.put('/', response);
  })());
});
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    for (const name of await caches.keys()) if (name.startsWith('vocabdna-pwa-') && name !== CACHE) await caches.delete(name);
    await self.clients.claim();
  })());
});
self.addEventListener('fetch', event => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== self.location.origin || url.pathname.startsWith('/api/') || /signin|signout|callback/.test(url.pathname)) return;
  if (event.request.mode === 'navigate' && url.pathname === '/') {
    event.respondWith(fetch(event.request).catch(async () => (await caches.open(CACHE)).match('/')));
  } else if (ASSETS.includes(url.pathname)) {
    event.respondWith((async () => (await (await caches.open(CACHE)).match(url.pathname)) || fetch(event.request))());
  }
});
`;
await writeFile(path.join(root, 'sw.js'), source);
console.log(`PWA: ${urls.length} offline assets, version ${version}`);
